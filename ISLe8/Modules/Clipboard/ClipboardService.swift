import AppKit
import CryptoKit

/// Records what you copy and puts it back on request.
///
/// macOS has no "pasteboard changed" notification, so this checks the pasteboard's change
/// counter twice a second. Reading the counter is a single integer and is not considered
/// reading the pasteboard. The content is only read once the counter moves, and only if
/// the user has allowed ISLe8 to read the pasteboard, so no system alert ever pops up in
/// the background.
@Observable
final class ClipboardService {
    enum Access {
        case allowed
        /// macOS would show an alert on every read until the user chooses "Always allow".
        case needsPermission
        case denied
    }

    private(set) var items: [ClipboardItem] = []
    private(set) var access: Access = .needsPermission
    private(set) var isStoreAvailable = true
    /// Briefly set after an item was copied, for the check mark.
    private(set) var lastCopiedID: Int64?
    var query = "" {
        didSet { reload() }
    }

    @ObservationIgnored private let settings: SettingsStore
    @ObservationIgnored private let folder: URL
    @ObservationIgnored private var store: ClipboardStore?
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChangeCount = 0
    /// The change count after ISLe8's own write, which must not be recorded again.
    @ObservationIgnored private var ownChangeCount = -1
    @ObservationIgnored private var copiedResetTask: Task<Void, Never>?

    private static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        // nspasteboard.org markers that password managers and similar apps set.
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    ]
    private static let maxTextLength = 1_000_000
    private static let maxRTFSize = 2_000_000
    private static let maxImageSize = 25_000_000

    init(settings: SettingsStore, folder: URL) {
        self.settings = settings
        self.folder = folder
        settings.onModuleSettingsChange { [weak self] in self?.applySettings() }
    }

    func start() {
        if store == nil {
            store = ClipboardStore(folder: folder)
            isStoreAvailable = store != nil
        }
        refreshAccess()
        reload()
        applySettings()
    }

    func stop() {
        stopWatching()
        store?.close()
        store = nil
    }

    // MARK: Permission

    func refreshAccess() {
        let current: Access
        if #available(macOS 15.4, *) {
            switch NSPasteboard.general.accessBehavior {
            case .alwaysAllow: current = .allowed
            case .alwaysDeny: current = .denied
            default: current = .needsPermission
            }
        } else {
            current = .allowed
        }
        if current != access {
            access = current
        }
    }

    /// Reads the pasteboard once on purpose. That shows the system alert and, from then on,
    /// lists ISLe8 in System Settings where "Always allow" can be chosen.
    func requestAccess() {
        _ = NSPasteboard.general.string(forType: .string)
        Task {
            try? await Task.sleep(for: .seconds(1))
            refreshAccess()
        }
    }

    func openPrivacySettings() {
        if let url = URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Pasteboard") {
            NSWorkspace.shared.open(url)
        }
    }

    // MARK: Watching

    private func applySettings() {
        if settings.recordClipboard && store != nil {
            startWatching()
        } else {
            stopWatching()
        }
    }

    private func startWatching() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { _ in
            MainActor.assumeIsolated { self.checkPasteboard() }
        }
        // Lets macOS line the wake-ups up with others.
        timer.tolerance = 0.25
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func stopWatching() {
        timer?.invalidate()
        timer = nil
    }

    private func checkPasteboard() {
        let pasteboard = NSPasteboard.general
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        guard changeCount != ownChangeCount else { return }

        refreshAccess()
        guard access == .allowed else { return }
        let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let app, settings.clipboardExcludedApps.contains(app) { return }
        guard let capture = Self.read(pasteboard) else { return }
        record(capture, app: app)
    }

    private func record(_ capture: ClipboardCapture, app: String?) {
        guard let store else { return }
        let now = Date()
        if let existing = store.id(forHash: capture.hash) {
            store.touch(existing, at: now, app: app)
        } else {
            var imageName: String?
            if let png = capture.imagePNG {
                let name = UUID().uuidString + ".png"
                do {
                    try png.write(to: store.imagesFolder.appending(path: name))
                    imageName = name
                } catch {
                    return
                }
            }
            store.insert(capture, imageName: imageName, app: app, at: now)
        }
        store.prune(keeping: settings.clipboardLimit, maxAge: Double(settings.clipboardMaxAgeDays) * 86_400)
        reload()
    }

    private static func read(_ pasteboard: NSPasteboard) -> ClipboardCapture? {
        guard let types = pasteboard.types, !types.contains(where: skippedTypes.contains) else { return nil }

        // Finder puts both file URLs and their names on the pasteboard; the files win.
        if types.contains(.fileURL),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let paths = urls.map(\.path).joined(separator: "\n")
            return ClipboardCapture(kind: .files, text: paths, hash: hash("files", Data(paths.utf8)))
        }

        if let string = pasteboard.string(forType: .string),
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard string.utf16.count <= maxTextLength else { return nil }
            let textHash = hash("text", Data(string.utf8))
            if isWebURL(string) {
                return ClipboardCapture(kind: .url, text: string, hash: textHash)
            }
            if types.contains(.rtf), let rtf = pasteboard.data(forType: .rtf), rtf.count <= maxRTFSize {
                return ClipboardCapture(kind: .richText, text: string, rtf: rtf, hash: textHash)
            }
            return ClipboardCapture(kind: .text, text: string, hash: textHash)
        }

        if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff), data.count <= maxImageSize {
            let png = types.contains(.png)
                ? data
                : NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:])
            guard let png else { return nil }
            return ClipboardCapture(kind: .image, text: "", imagePNG: png, hash: hash("image", png))
        }
        return nil
    }

    private static func isWebURL(_ string: String) -> Bool {
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.contains(where: \.isWhitespace), let url = URL(string: trimmed) else { return false }
        return url.scheme == "http" || url.scheme == "https"
    }

    private static func hash(_ kind: String, _ data: Data) -> String {
        var hasher = SHA256()
        hasher.update(data: Data(kind.utf8))
        hasher.update(data: data)
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }

    // MARK: Using the history

    func reload() {
        items = store?.items(matching: query, limit: max(settings.clipboardLimit, 50) + 50) ?? []
    }

    /// Matches for the command palette, without touching the clipboard tab's own search.
    func search(_ text: String, limit: Int) -> [ClipboardItem] {
        store?.items(matching: text, limit: limit) ?? []
    }

    func imageURL(for item: ClipboardItem) -> URL? {
        guard let name = item.imageName, let store else { return nil }
        return store.imagesFolder.appending(path: name)
    }

    /// Puts the item back on the pasteboard and moves it to the top of the history.
    func copy(_ item: ClipboardItem) {
        guard let store, let content = store.content(of: item.id) else { return }
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.kind {
        case .text:
            pasteboard.setString(content.text, forType: .string)
        case .richText:
            pasteboard.declareTypes([.rtf, .string], owner: nil)
            if let rtf = content.rtf {
                pasteboard.setData(rtf, forType: .rtf)
            }
            pasteboard.setString(content.text, forType: .string)
        case .url:
            pasteboard.declareTypes([.URL, .string], owner: nil)
            pasteboard.setString(content.text, forType: .URL)
            pasteboard.setString(content.text, forType: .string)
        case .image:
            if let name = content.imageName, let image = NSImage(contentsOf: store.imagesFolder.appending(path: name)) {
                pasteboard.writeObjects([image])
            }
        case .files:
            let urls = content.text.split(separator: "\n").map { URL(fileURLWithPath: String($0)) as NSURL }
            pasteboard.writeObjects(urls)
        }
        ownChangeCount = pasteboard.changeCount
        store.touch(item.id, at: Date(), app: nil)
        reload()

        lastCopiedID = item.id
        copiedResetTask?.cancel()
        copiedResetTask = Task {
            try? await Task.sleep(for: .seconds(1.2))
            guard !Task.isCancelled else { return }
            lastCopiedID = nil
        }
    }

    /// Copies the item and reports whether ISLe8 may press ⌘V for you. Pressing keys in
    /// another app needs Accessibility permission; the first attempt asks for it.
    func prepareToPaste(_ item: ClipboardItem) -> Bool {
        copy(item)
        if AXIsProcessTrusted() {
            return true
        }
        AXIsProcessTrustedWithOptions(["AXTrustedCheckOptionPrompt": true] as CFDictionary)
        return false
    }

    static func pressPaste() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let keyV: CGKeyCode = 9
        for isDown in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: keyV, keyDown: isDown)
            event?.flags = .maskCommand
            event?.post(tap: .cghidEventTap)
        }
    }

    func togglePin(_ item: ClipboardItem) {
        store?.setPinned(item.id, !item.isPinned)
        reload()
    }

    func delete(_ item: ClipboardItem) {
        store?.delete(item.id)
        reload()
    }

    func clearHistory() {
        store?.deleteAll(keepingPinned: true)
        reload()
    }
}
